#Дано трехзначное число. В нем зачеркнули первую справа цифру и приписали ее слева. Вывести полученное число

n = int(input("Введите трехзначное число: "))

while type(n) != int:
    try:
        n = int(n)
    except ValueError:
        print("число введено неппраивльо")
        n = int(input("Введите трехзначное число: "))

last = n % 10

first = n // 10

res = last * 100 + first

print("Полученное число:", res)